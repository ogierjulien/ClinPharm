export function exportPlotImage(svgElement: SVGElement, filename: string, format: 'svg' | 'png' = 'png'): void {
  if (format === 'svg') {
    const serializer = new XMLSerializer();
    const svgStr = serializer.serializeToString(svgElement);
    const blob = new Blob([svgStr], { type: 'image/svg+xml' });
    downloadBlob(blob, filename);
    return;
  }

  const canvas = document.createElement('canvas');
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  const serializer = new XMLSerializer();
  const svgStr = serializer.serializeToString(svgElement);
  const img = new Image();
  const url = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svgStr)));
  img.onload = () => {
    canvas.width = img.width || 800;
    canvas.height = img.height || 600;
    ctx.drawImage(img, 0, 0);
    canvas.toBlob(blob => {
      if (blob) downloadBlob(blob, filename);
    }, 'image/png');
  };
  img.src = url;
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function formatNumber(v: number | undefined | null, decimals = 3): string {
  if (v === undefined || v === null || isNaN(v)) return '—';
  if (Math.abs(v) >= 10000 || (Math.abs(v) < 0.001 && v !== 0)) {
    return v.toExponential(2);
  }
  return v.toFixed(decimals);
}

export function formatFoldError(fe: number | undefined): string {
  if (fe === undefined || isNaN(fe)) return '—';
  const val = fe >= 1 ? fe : 1 / fe;
  const dir = fe >= 1 ? '↑' : '↓';
  return `${val.toFixed(2)}× ${dir}`;
}

// Generate allometry report HTML content
export function buildAllometryReportHTML(result: AllometrySessionResult): string {
  const { compound, inputs, finalResults, warnings, assumptions, metadata } = result;
  let html = `<h1>Allometric Scaling Report</h1>`;
  html += `<p><strong>Compound:</strong> ${compound.name}</p>`;
  html += `<p><strong>Run ID:</strong> ${metadata.runId}</p>`;
  html += `<p><strong>Date:</strong> ${metadata.timestamp}</p>`;

  html += `<h2>Input Data</h2>`;
  html += `<table><tr><th>Species</th><th>BW (kg)</th><th>CL (mL/min)</th><th>Vss (L)</th><th>fup</th></tr>`;
  for (const d of inputs.animalData.filter(x => x.include)) {
    html += `<tr><td>${d.label}</td><td>${d.bodyWeight_kg}</td><td>${formatNumber(d.CL_abs)}</td><td>${formatNumber(d.Vss_abs)}</td><td>${d.fup ?? '—'}</td></tr>`;
  }
  html += `</table>`;

  html += `<h2>Results by Method</h2>`;
  for (const r of finalResults.methodResults) {
    html += `<h3>${r.label}</h3>`;
    if (r.regressionCL) {
      html += `<div class="equation">CL = ${formatNumber(r.regressionCL.a, 4)} × BW<sup>${formatNumber(r.regressionCL.slope, 3)}</sup> &nbsp; R²=${formatNumber(r.regressionCL.rSquared, 4)}</div>`;
    }
    if (r.predictedCL_human !== undefined) {
      html += `<p>Predicted Human CL: <strong>${formatNumber(r.predictedCL_human)} mL/min</strong></p>`;
    }
    if (r.predictedVss_human !== undefined) {
      html += `<p>Predicted Human Vss: <strong>${formatNumber(r.predictedVss_human)} L</strong></p>`;
    }
    if (r.AAFE_CL !== undefined) {
      html += `<p>AAFE (CL): ${formatNumber(r.AAFE_CL, 3)}</p>`;
    }
  }

  if (warnings.length > 0) {
    html += `<h2>Warnings</h2>`;
    for (const w of warnings) {
      html += `<div class="warning">[${w.severity.toUpperCase()}] ${w.message}</div>`;
    }
  }

  if (assumptions.length > 0) {
    html += `<h2>Assumptions</h2><ul>`;
    for (const a of assumptions) html += `<li>${a}</li>`;
    html += `</ul>`;
  }

  return html;
}
