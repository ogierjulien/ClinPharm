// ---------------------------------------------------------------------------
// JSON export
// ---------------------------------------------------------------------------

export function exportJSON(
  result: AllometrySessionResult | IVIVESessionResult | DDISessionResult,
  filename?: string
): void {
  const json = JSON.stringify(result, null, 2);
  const blob = new Blob([json], { type: 'application/json' });
  downloadBlob(blob, filename ?? `clinpharm-run-${result.metadata.runId}.json`);
}

// ---------------------------------------------------------------------------
// CSV export helpers
// ---------------------------------------------------------------------------

export function exportCSV(rows: Record<string, unknown>[], filename: string): void {
  if (rows.length === 0) return;
  const headers = Object.keys(rows[0]);
  const lines = [
    headers.join(','),
    ...rows.map(row =>
      headers.map(h => {
        const v = row[h];
        const s = v === null || v === undefined ? '' : String(v);
        return s.includes(',') || s.includes('"') || s.includes('\n')
          ? `"${s.replace(/"/g, '""')}"`
          : s;
      }).join(',')
    ),
  ];
  const blob = new Blob([lines.join('\n')], { type: 'text/csv' });
  downloadBlob(blob, filename);
}

